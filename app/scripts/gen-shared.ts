/**
 * Generates src/shared/generated/*.ts from the repository-level /shared/*.json
 * contracts. Run `npm run gen:shared` after editing /shared; `--check` (used by
 * `npm run verify`) fails if the committed output is stale.
 */
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';

import { canonicalJson } from './canonical';

const APP_ROOT = resolve(__dirname, '..');
const SHARED_DIR = resolve(APP_ROOT, '..', 'shared');
const OUT_DIR = join(APP_ROOT, 'src', 'shared', 'generated');

type Json = Record<string, any>; // eslint-disable-line @typescript-eslint/no-explicit-any

const HEADER =
  '// AUTO-GENERATED by app/scripts/gen-shared.ts from /shared — DO NOT EDIT.\n' +
  '// Run `npm run gen:shared` after changing the JSON contracts.\n\n';

function load(name: string): Json {
  return JSON.parse(readFileSync(join(SHARED_DIR, `${name}.json`), 'utf8')) as Json;
}

function lit(value: unknown): string {
  return JSON.stringify(value, null, 2);
}

export function uuidFor(template: string, suffix: string): string {
  if (!/^[0-9A-Fa-f]{4}$/.test(suffix)) throw new Error(`bad UUID suffix ${suffix}`);
  return template.replace('XXXX', suffix).toLowerCase();
}

export function featureSpecHash(spec: Json): string {
  const payload = { version: spec.version, features: spec.features, classes: spec.classes };
  return createHash('sha256').update(canonicalJson(payload), 'utf8').digest('hex');
}

export function renderGatt(spec: Json): string {
  const tpl: string = spec.uuidTemplate;
  const services: Record<string, string> = {};
  const chars: Json[] = [];
  for (const svc of spec.services) {
    services[svc.key] = uuidFor(tpl, svc.suffix);
    for (const c of svc.characteristics) {
      chars.push({
        key: c.key,
        uuid: uuidFor(tpl, c.suffix),
        service: svc.key,
        serviceUuid: services[svc.key],
        type: c.type,
        unit: c.unit,
        props: c.props,
      });
    }
  }
  const pkt = spec.telemetryPacket;
  const telemetry = {
    uuid: pkt.suffix ? uuidFor(tpl, pkt.suffix) : null,
    alignedSize: pkt.alignedSize,
    packedSize: pkt.packedSize,
    fields: pkt.fields,
  };
  return (
    HEADER +
    `export const GATT_SPEC_VERSION = ${lit(spec.version)};\n\n` +
    `export const ADVERTISED_SERVICE_UUID = ${lit(uuidFor(tpl, spec.advertisedServiceSuffix))};\n\n` +
    `export const DEVICE_NAMES = ${lit(spec.deviceNames)} as const;\n\n` +
    `export const ROLE_CODES = ${lit(spec.roleCodes)} as const;\n\n` +
    `export const BLE_MODES = ${lit(spec.bleModes)} as const;\n\n` +
    `export const SERVICE_UUIDS = ${lit(services)} as const;\n\n` +
    `export const CHARACTERISTICS = ${lit(chars)} as const;\n\n` +
    `export const TELEMETRY_PACKET = ${lit(telemetry)} as const;\n`
  );
}

export function renderLabels(cat: Json): string {
  const labels = cat.labels.map((l: Json) => ({
    id: l.id,
    key: l.key,
    name: l.name,
    kind: l.kind,
    group: l.group,
    pairId: l.pairId ?? null,
    trainingClass: l.trainingClass ?? null,
  }));
  return (
    HEADER +
    `export const LABEL_CATALOG_VERSION = ${lit(cat.version)};\n\n` +
    `export const VOID_LABEL_ID = ${lit(cat.voidId)};\n\n` +
    `export const LABELS = ${lit(labels)} as const;\n`
  );
}

export function renderFeatures(spec: Json): string {
  return (
    HEADER +
    `export const FEATURE_SPEC_VERSION = ${lit(spec.version)};\n\n` +
    `export const FEATURE_SPEC_HASH = ${lit(featureSpecHash(spec))};\n\n` +
    `export const FEATURE_KEYS = ${lit(spec.features.map((f: Json) => f.key))} as const;\n\n` +
    `export const CLASS_NAMES = ${lit(spec.classes)} as const;\n\n` +
    `export const NO_INFERENCE_LABEL = ${lit(spec.noInferenceLabel)};\n\n` +
    `export const FREEZE_OVERRIDE_DEFAULTS = ${lit({
      classIndex: spec.freezeOverride.classIndex,
      threshold: spec.freezeOverride.threshold,
      consecutiveStrides: spec.freezeOverride.consecutiveStrides,
    })} as const;\n`
  );
}

const REPLAY_COLUMNS = [
  'timestamp_us',
  'sampleIndex',
  'strideTimeS',
  'swingTimeS',
  'stanceTimeS',
  'strideLengthM',
  'tibialShockG',
  'asymmetryIndex',
  'freezeIndex',
] as const;

/** Firmware stride CSV -> compact replay table (columns in REPLAY_COLUMNS order). */
export function renderReplay(csvText: string, source: string): string {
  const lines = csvText.trim().split(/\r?\n/);
  const header = lines[0]!.split(',').map((h) => h.trim());
  const idx = REPLAY_COLUMNS.map((c) => {
    const i = header.indexOf(c);
    if (i < 0) throw new Error(`${source}: missing column ${c}`);
    return i;
  });
  const rows = lines.slice(1).map((line, n) => {
    const cells = line.split(',');
    return idx.map((i) => {
      const v = Number(cells[i]);
      if (!Number.isFinite(v)) throw new Error(`${source}: bad number in row ${n + 1}`);
      return v;
    });
  });
  return (
    HEADER +
    `/** Source: ${source} (${rows.length} strides, left ankle, healthy adult). */\n` +
    `export const REPLAY_0007_COLUMNS = ${lit(REPLAY_COLUMNS)} as const;\n\n` +
    `export const REPLAY_0007_ROWS: readonly (readonly number[])[] = [\n` +
    rows.map((r) => `  [${r.join(', ')}],`).join('\n') +
    `\n];\n`
  );
}

const REPLAY_SOURCE = 'data/reference/session_0007/S_L_0007.CSV';

export function renderAll(): Record<string, string> {
  const replayCsv = readFileSync(resolve(APP_ROOT, '..', REPLAY_SOURCE), 'utf8');
  return {
    'gatt.ts': renderGatt(load('gatt_spec')),
    'labels.ts': renderLabels(load('label_catalog')),
    'features.ts': renderFeatures(load('feature_spec')),
    'replay0007.ts': renderReplay(replayCsv, REPLAY_SOURCE),
  };
}

function main(): void {
  const check = process.argv.includes('--check');
  const outputs = renderAll();
  const stale: string[] = [];
  for (const [file, content] of Object.entries(outputs)) {
    const path = join(OUT_DIR, file);
    const current = existsSync(path) ? readFileSync(path, 'utf8') : null;
    if (current === content) continue;
    if (check) {
      stale.push(file);
    } else {
      mkdirSync(dirname(path), { recursive: true });
      writeFileSync(path, content);
      console.log(`wrote ${path}`);
    }
  }
  if (stale.length) {
    console.error(`stale generated files: ${stale.join(', ')} — run \`npm run gen:shared\``);
    process.exit(1);
  }
  if (check) console.log('shared contracts: generated files are up to date');
}

if (require.main === module) main();
