"""Export a trained model for the phone and the firmware (M10).

Artifacts:
  model.tflite         float32, raw features; normalisation is inside the graph
  model_int8.tflite    full-integer quantised, for TFLite Micro on the nRF52840.
                       Its input is **normalised** (see feature_spec.h): one
                       int8 scale is shared by every feature, so raw units
                       (cadence ~480 vs stride time ~1.3) would quantise the
                       small features to a single level.
  model_data.h         int8 flatbuffer as a C array (alignas(16)), no xxd needed
  feature_spec.h       feature order, class names, feature-spec hash and the
                       normalisation constants the firmware applies first
  golden_vectors.h     normalised inputs + expected int8 argmax, for the firmware
  golden_vectors.json  the same plus raw inputs and float probabilities
  mlp_weights.json     normalisation + dense weights; the app runs this MLP in
                       TypeScript and is tested to reproduce model.tflite
  model_meta.json      versions, hashes, sizes, checks; the app refuses a model
                       whose featureSpecHash does not match its own
"""

from __future__ import annotations

import hashlib
import json
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import numpy as np
import numpy.typing as npt

from .shared import class_names, feature_names, feature_spec_hash

# TFLite Micro kernels the firmware must register; anything else fails export.
ALLOWED_OPS = frozenset(
    {
        "FULLY_CONNECTED",
        "RELU",
        "SOFTMAX",
        "QUANTIZE",
        "DEQUANTIZE",
        "SUB",
        "MUL",
        "ADD",
        "RSQRT",
        "MAXIMUM",
    }
)
MAX_INT8_BYTES = 8 * 1024
MIN_INT8_AGREEMENT = 0.98
KERAS_NORMALIZATION_EPSILON = 1e-7  # keras.backend.epsilon(), used by Normalization


class ExportError(RuntimeError):
    pass


@dataclass
class ExportResult:
    out_dir: Path
    float_bytes: int
    int8_bytes: int
    ops: list[str]
    int8_agreement: float


def _tf() -> Any:
    import tensorflow as tf

    return tf


def to_tflite(model: Any, rep_X: npt.NDArray[np.float32] | None) -> bytes:
    tf = _tf()
    conv = tf.lite.TFLiteConverter.from_keras_model(model)
    if rep_X is not None:
        conv.optimizations = [tf.lite.Optimize.DEFAULT]

        def rep() -> Any:
            for row in rep_X[: min(len(rep_X), 500)]:
                yield [row.reshape(1, -1).astype(np.float32)]

        conv.representative_dataset = rep
        conv.target_spec.supported_ops = [tf.lite.OpsSet.TFLITE_BUILTINS_INT8]
        conv.inference_input_type = tf.int8
        conv.inference_output_type = tf.int8
    data: bytes = conv.convert()
    return data


class TfliteRunner:
    """Runs a .tflite model on the features the model expects (raw or normalised),
    handling int8 (de)quantisation.

    Delegates are disabled on purpose: the default XNNPACK delegate reports
    itself as a synthetic DELEGATE node and can change int8 results, while the
    firmware runs plain TFLite Micro kernels, so the checks must see the same
    graph the firmware will.
    """

    def __init__(self, flatbuffer: bytes) -> None:
        tf = _tf()
        self.interp = tf.lite.Interpreter(
            model_content=flatbuffer,
            experimental_op_resolver_type=(
                tf.lite.experimental.OpResolverType.BUILTIN_WITHOUT_DEFAULT_DELEGATES
            ),
        )
        self.interp.allocate_tensors()
        self.inp = self.interp.get_input_details()[0]
        self.out = self.interp.get_output_details()[0]

    def ops(self) -> list[str]:
        return sorted({op["op_name"] for op in self.interp._get_ops_details()})

    def predict(self, X: npt.NDArray[np.float32]) -> npt.NDArray[np.float32]:
        out = np.zeros((len(X), len(class_names())), dtype=np.float32)
        for i, row in enumerate(X):
            x = row.reshape(1, -1).astype(np.float32)
            if self.inp["dtype"] == np.int8:
                scale, zero = self.inp["quantization"]
                x = np.clip(np.round(x / scale + zero), -128, 127).astype(np.int8)
            self.interp.set_tensor(self.inp["index"], x)
            self.interp.invoke()
            y = self.interp.get_tensor(self.out["index"])[0]
            if self.out["dtype"] == np.int8:
                scale, zero = self.out["quantization"]
                y = (y.astype(np.float32) - zero) * scale
            out[i] = y
        return out


def _c_array(name: str, data: bytes) -> str:
    lines = []
    for i in range(0, len(data), 12):
        lines.append("  " + ", ".join(f"0x{b:02x}" for b in data[i : i + 12]) + ",")
    return (
        f"alignas(16) const unsigned char {name}[] = {{\n" + "\n".join(lines) + "\n};\n"
        f"const unsigned int {name}_len = {len(data)};\n"
    )


def model_data_h(int8_model: bytes) -> str:
    return (
        "// AUTO-GENERATED by ml/arcsense_ml/export.py - do not edit.\n"
        f"// feature_spec_hash: {feature_spec_hash()}\n"
        f"// sha256: {hashlib.sha256(int8_model).hexdigest()}\n"
        "#pragma once\n\n" + _c_array("g_arcsense_model", int8_model)
    )


def feature_spec_h(
    mean: npt.NDArray[np.float64] | None = None,
    scale: npt.NDArray[np.float64] | None = None,
) -> str:
    feats = feature_names()
    classes = class_names()
    norm = ""
    if mean is not None and scale is not None:
        mean_s = ", ".join(f"{v:.9g}f" for v in mean)
        scale_s = ", ".join(f"{v:.9g}f" for v in scale)
        norm = (
            "// The int8 model takes NORMALISED features. Compute them first:\n"
            "//   normalised[i] = (raw[i] - kNormMean[i]) * kNormScale[i]\n"
            "// Raw units differ by three orders of magnitude (cadence ~480 vs stride\n"
            "// time ~1.3), and int8 has one scale for the whole input tensor.\n"
            f"static const float kNormMean[{len(feats)}] = {{{mean_s}}};\n"
            f"static const float kNormScale[{len(feats)}] = {{{scale_s}}};\n\n"
        )
    return (
        "// AUTO-GENERATED by ml/arcsense_ml/export.py - do not edit.\n#pragma once\n\n"
        f'#define ARCSENSE_FEATURE_SPEC_HASH "{feature_spec_hash()}"\n'
        f"#define ARCSENSE_NUM_FEATURES {len(feats)}\n"
        f"#define ARCSENSE_NUM_CLASSES {len(classes)}\n\n"
        "// Input order. cadenceSpm = 120 / strideTimeS; swingRatio = swing / stride;\n"
        "// stanceRatio = stance / stride; asymmetryIndex is the firmware fraction.\n"
        "enum ArcsenseFeature {\n"
        + "".join(f"  ARCSENSE_F_{i}_{f} = {i},\n" for i, f in enumerate(feats))
        + "};\n\n"
        + norm
        + f"static const char *const kArcsenseClassNames["
        f"{len(classes)}] = {{" + ", ".join(f'"{c}"' for c in classes) + "};\n"
    )


def golden_vectors(
    X: npt.NDArray[np.float32],
    float_runner: TfliteRunner,
    int8_runner: TfliteRunner,
    mean: npt.NDArray[np.float64],
    scale: npt.NDArray[np.float64],
) -> dict[str, Any]:
    Xn = normalize_features(X, mean, scale)
    pf = float_runner.predict(X)
    pi = int8_runner.predict(Xn)
    return {
        "featureSpecHash": feature_spec_hash(),
        "features": feature_names(),
        "classes": class_names(),
        # "inputs" is what the int8 model (and the firmware) consumes.
        "inputs": Xn.astype(float).round(6).tolist(),
        "rawInputs": X.astype(float).round(6).tolist(),
        "floatProbs": pf.astype(float).round(6).tolist(),
        "int8Probs": pi.astype(float).round(6).tolist(),
        "floatArgmax": pf.argmax(axis=1).tolist(),
        "int8Argmax": pi.argmax(axis=1).tolist(),
    }


def golden_vectors_h(g: dict[str, Any]) -> str:
    n = len(g["inputs"])
    rows = ",\n".join("  {" + ", ".join(f"{v:.6f}f" for v in r) + "}" for r in g["inputs"])
    arg = ", ".join(str(a) for a in g["int8Argmax"])
    return (
        "// AUTO-GENERATED by ml/arcsense_ml/export.py - do not edit.\n#pragma once\n"
        '#include "feature_spec.h"\n\n'
        f"#define ARCSENSE_NUM_GOLDEN {n}\n"
        f"static const float kGoldenInputs[{n}][ARCSENSE_NUM_FEATURES] = {{\n{rows}\n}};\n"
        f"// expected int8 model argmax for each input\n"
        f"static const int kGoldenArgmax[{n}] = {{{arg}}};\n"
    )


def normalization_params(model: Any) -> tuple[npt.NDArray[np.float64], npt.NDArray[np.float64]]:
    """The Normalization layer's mean and 1/std, as baked into the float graph."""
    norm = model.get_layer("normalize")
    mean = np.asarray(norm.mean, dtype=np.float64).reshape(-1)
    var = np.asarray(norm.variance, dtype=np.float64).reshape(-1)
    scale = 1.0 / np.sqrt(var + KERAS_NORMALIZATION_EPSILON)
    return mean, scale


def normalize_features(
    X: npt.NDArray[np.float32],
    mean: npt.NDArray[np.float64],
    scale: npt.NDArray[np.float64],
) -> npt.NDArray[np.float32]:
    """(x - mean) * scale, the same arithmetic the float graph does internally."""
    return np.asarray((X.astype(np.float64) - mean) * scale, dtype=np.float32)


def model_without_normalization(model: Any) -> Any:
    """The same dense stack with the Normalization layer removed, so its input is
    already-normalised features and a single int8 scale is usable."""
    tf = _tf()
    inp = tf.keras.Input(shape=(len(feature_names()),), name="features_norm", dtype="float32")
    h = inp
    for layer in model.layers:
        if layer.__class__.__name__ == "Dense":
            h = layer(h)
    return tf.keras.Model(inp, h, name="arcsense_gait_norm")


def mlp_weights(model: Any, version: str) -> dict[str, Any]:
    """Weights in a framework-free form: y = softmax(...relu(W x + b)...)."""
    norm = model.get_layer("normalize")
    mean = np.asarray(norm.mean, dtype=np.float64).reshape(-1)
    var = np.asarray(norm.variance, dtype=np.float64).reshape(-1)
    layers = []
    for layer in model.layers:
        if layer.__class__.__name__ != "Dense":
            continue
        kernel, bias = layer.get_weights()
        layers.append(
            {
                "kernel": np.asarray(kernel, dtype=np.float64).tolist(),
                "bias": np.asarray(bias, dtype=np.float64).tolist(),
                "activation": layer.get_config()["activation"],
            }
        )
    return {
        "version": version,
        "featureSpecHash": feature_spec_hash(),
        "normalization": {
            "mean": mean.tolist(),
            "variance": var.tolist(),
            "epsilon": KERAS_NORMALIZATION_EPSILON,
        },
        "layers": layers,
    }


def export_model(
    model: Any,
    rep_X: npt.NDArray[np.float32],
    golden_X: npt.NDArray[np.float32],
    out_dir: str | Path,
    *,
    version: str,
    trained_on: dict[str, Any],
) -> ExportResult:
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    mean, scale = normalization_params(model)
    float_model = to_tflite(model, None)
    int8_model = to_tflite(
        model_without_normalization(model), normalize_features(rep_X, mean, scale)
    )
    fr, ir = TfliteRunner(float_model), TfliteRunner(int8_model)

    ops = ir.ops()
    bad = sorted(set(ops) - ALLOWED_OPS)
    if bad:
        raise ExportError(f"int8 model uses ops not registered on the firmware: {bad}")
    if len(int8_model) > MAX_INT8_BYTES:
        raise ExportError(f"int8 model is {len(int8_model)} bytes (limit {MAX_INT8_BYTES})")
    Xn = normalize_features(rep_X, mean, scale)
    agree = float(np.mean(fr.predict(rep_X).argmax(1) == ir.predict(Xn).argmax(1)))
    if agree < MIN_INT8_AGREEMENT:
        raise ExportError(f"int8 top-1 agreement {agree:.3f} < {MIN_INT8_AGREEMENT}")

    g = golden_vectors(golden_X, fr, ir, mean, scale)
    (out / "model.tflite").write_bytes(float_model)
    (out / "model_int8.tflite").write_bytes(int8_model)
    (out / "model_data.h").write_text(model_data_h(int8_model))
    (out / "feature_spec.h").write_text(feature_spec_h(mean, scale))
    (out / "golden_vectors.h").write_text(golden_vectors_h(g))
    (out / "golden_vectors.json").write_text(json.dumps(g, indent=1) + "\n")
    (out / "mlp_weights.json").write_text(json.dumps(mlp_weights(model, version)) + "\n")
    meta = {
        "version": version,
        "featureSpecHash": feature_spec_hash(),
        "features": feature_names(),
        "classes": class_names(),
        "floatSha256": hashlib.sha256(float_model).hexdigest(),
        "int8Sha256": hashlib.sha256(int8_model).hexdigest(),
        "floatBytes": len(float_model),
        "int8Bytes": len(int8_model),
        "int8Ops": ops,
        "int8Agreement": agree,
        "int8Input": "normalized: (raw - kNormMean) * kNormScale, see feature_spec.h",
        "trainedOn": trained_on,
    }
    (out / "model_meta.json").write_text(json.dumps(meta, indent=1) + "\n")
    return ExportResult(out, len(float_model), len(int8_model), ops, agree)
